#!/bin/bash
# 求职研究栏目：从工作区源文件同步 → 脱敏 → 修死链 的固定流程
# 用法: bash scripts/sync-career.sh
set -e
S="/d/ai资料/实习/career_research"
D="/d/ai资料/日常与规划/求职研究"

# 同步（源文件 → 站点文件名）
cp "$S/01_岗位方向/岗位地图.md"                 "$D/岗位地图.md"
cp "$S/01_岗位方向/能力矩阵.md"                 "$D/能力矩阵.md"
cp "$S/01_岗位方向/岗位可得性与竞争矩阵.md"     "$D/岗位可得性与竞争矩阵.md"
cp "$S/02_技术路线/技术栈优先级.md"             "$D/技术栈优先级.md"
cp "$S/02_技术路线/官方资料清单.md"             "$D/官方资料清单.md"
cp "$S/04_实习申请/简历项目写法.md"             "$D/简历项目写法.md"
cp "$S/04_实习申请/申请与避坑.md"               "$D/申请与避坑.md"
cp "$S/09_岗位运营规则/评分规则.md"             "$D/岗位评分规则.md"
cp "$S/09_岗位运营规则/异常处理规则.md"         "$D/岗位检索异常处理.md"
cp "$S/06_资料来源/每日岗位搜索源与查询词.md"   "$D/岗位搜索源与查询词.md"
cp "$S/05_时间规划/大学整体实习规划.md"         "$D/大学整体实习规划.md"

cd "$D"
# —— 脱敏：校名/城市/个人语境 ——
sed -i 's/西电电子信息背景加成/电子信息背景加成/g; s/西电优势/学校资源优势/g; s/西电背景应换成技术密度更高的机会/电子信息背景应主动选择技术密度更高的机会/g; s/仍是西电电子信息背景的高匹配候选/仍是电子信息背景的高匹配候选/g; s/西电/学校平台/g' 岗位地图.md 大学整体实习规划.md 岗位可得性与竞争矩阵.md 2>/dev/null || true
# —— 死链：指向未上站文件一律删除或改文字 ——
# 通用清理：删除指向 未上站文档 的整行链接引用改为纯文字
perl -0pi -e 's|\[([^\]]+)\]\((?:\.\./|0[05-8])[^)]*\)|$1（本地文档，未随站发布）|g' *.md 2>/dev/null || true
perl -0pi -e 's|\[([^\]]+)\]\(\.\./[^)]*\)|$1|g' *.md 2>/dev/null || true
perl -0pi -e 's|\]\((?:\.\./)?(?:00_个人求职画像|05_时间规划|01_岗位方向/岗位可得性)[^)]*\)|()|g' *.md 2>/dev/null || true
# 申请与避坑：城市分级泛化
sed -i 's/城市 A\/B\/C 分级[^；*]*//g; s/城市按本人 A\/B\/C 分级筛选/城市按“核心\/次级\/探索”三级筛选/g' 申请与避坑.md 2>/dev/null || true
sed -i 's/固定记录西安及深圳、上海、杭州、北京的供给/优先记录一线城市及新一线城市的供给/g' 申请与避坑.md 2>/dev/null || true
# 搜索源：城市词泛化
sed -i 's/城市词固定查 `西安`，每日再轮换一个 `深圳`、`上海`、`杭州`、`北京`/城市词固定查所在城市，每日再轮换一个一线\/新一线城市/g; s/西安每天必查不变/所在城市每天必查不变/g' 岗位搜索源与查询词.md 2>/dev/null || true
echo "同步完成。请运行安全扫描确认。"
